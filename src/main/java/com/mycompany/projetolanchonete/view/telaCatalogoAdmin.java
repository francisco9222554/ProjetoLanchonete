    private void jToggleButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButton1ActionPerformed
        try {
        String nome = jTextField2.getText().trim();
        String categoria = jTextField3.getText().trim();
        String precoStr = jTextField4.getText().trim().replace(",", ".");

        if (nome.isEmpty() || nome.equals("") ||
            categoria.isEmpty() || categoria.equals("") ||
            precoStr.isEmpty() || precoStr.equals("")) {
            JOptionPane.showMessageDialog(this, "Preencha todos os campos!");
            return;
        }

        double preco = Double.parseDouble(precoStr);
        ProdutoDao dao = new ProdutoDao();

        if (idSelecionado == 0) {
            dao.cadastrar(new Produto(nome, categoria, preco));
            JOptionPane.showMessageDialog(this, "Produto cadastrado com sucesso!");
        } else {
            Produto p = new Produto(idSelecionado, nome, categoria, preco);
            dao.atualizar(p);
            JOptionPane.showMessageDialog(this, "Produto atualizado com sucesso!");
        }

        carregarTabela();
        limparCampos();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Preço inválido! Use apenas números.", "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jToggleButton1ActionPerformed

