    private void jToggleButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButton3ActionPerformed
        int linha = jTable1.getSelectedRow();
        
        if (linha == -1) {
        JOptionPane.showMessageDialog(this, "Selecione um produto na tabela para atualizar!");
        return;
    }

    Produto p = listaProdutos.get(linha);
    idSelecionado = p.getId();
    jTextField2.setText(p.getNome());
    jTextField3.setText(p.getCategoria());
    jTextField4.setText(String.valueOf(p.getPreco()));

    JOptionPane.showMessageDialog(this, "Dados carregados!\nAltere o que desejar e clique em \"Cadastrar Produto\" para salvar.");                                         
    }//GEN-LAST:event_jToggleButton3ActionPerformed

    private void jToggleButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButton2ActionPerformed
        int linha = jTable1.getSelectedRow();
    if (linha == -1) {
        JOptionPane.showMessageDialog(this, "Selecione um produto na tabela para deletar!");
        return;
    }

    Produto p = listaProdutos.get(linha);
    int conf = JOptionPane.showConfirmDialog(this,
            "Deseja realmente excluir o produto \"" + p.getNome() + "\"?",
            "Confirmar exclusão", JOptionPane.YES_NO_OPTION);

    if (conf == JOptionPane.YES_OPTION) {
        new ProdutoDao().excluir(p.getId());
        carregarTabela();
        limparCampos();
        JOptionPane.showMessageDialog(this, "Produto excluído!");
        }
    }//GEN-LAST:event_jToggleButton2ActionPerformed

